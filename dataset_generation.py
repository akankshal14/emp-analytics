import pandas as pd
import numpy as np
from faker import Faker

# 1. Load the original base IBM HR dataset
df_base = pd.read_csv("/content/WA_Fn-UseC_-HR-Employee-Attrition.csv")

# 2. Setup seeds for reproducibility
fake = Faker()
np.random.seed(42)
Faker.seed(42)

n_records = 100000

# 3. Resample base data up to 100k rows to preserve original feature distributions
df_100k = df_base.sample(n=n_records, replace=True).reset_index(drop=True)

# 4. Generate synthetic unique identities
df_100k['EmployeeID'] = [f"EMP-{100000 + i}" for i in range(n_records)]
df_100k['FirstName'] = [fake.first_name() for _ in range(n_records)]
df_100k['LastName'] = [fake.last_name() for _ in range(n_records)]

# 5. Standardize column names
df_100k['DepartmentName'] = df_100k['Department']
df_100k['LatestPerformanceRating'] = df_100k['PerformanceRating']

# 6. Synchronize Attrition status with IsActive and Dates
df_100k['IsActive'] = df_100k['Attrition'].apply(lambda x: 0 if x == 'Yes' else 1)

base_date = pd.to_datetime('2024-01-01')

# Calculate HireDate based on YearsAtCompany
df_100k['HireDate'] = [
    (base_date - pd.DateOffset(years=int(yrs))).strftime('%Y-%m-%d')
    for yrs in df_100k['YearsAtCompany']
]

# Assign TerminationDate for attrited employees (IsActive == 0)
df_100k['TerminationDate'] = [
    (base_date - pd.DateOffset(months=np.random.randint(1, 24))).strftime('%Y-%m-%d')
    if active == 0 else np.nan
    for active in df_100k['IsActive']
]

# 7. Add project metadata fields
project_names = ['Project Alpha', 'Project Beacon', 'Project Horizon', 'Project Synergy', 'Project Apex']
df_100k['AssignedProjectName'] = np.random.choice(project_names, size=n_records)
df_100k['ProjectAllocationPercentage'] = np.random.choice([25, 50, 75, 100], size=n_records)
df_100k['ActiveProjectCount'] = np.random.randint(1, 5, size=n_records)

# 8. Drop redundant/duplicate columns
drop_cols = ['Department', 'PerformanceRating', 'EmployeeCount', 'StandardHours', 'Over18', 'EmployeeNumber']
df_100k = df_100k.drop(columns=[col for col in drop_cols if col in df_100k.columns])

# 9. Save to CSV file
output_filename = 'IBM_HR_Unified_100k_With_Attrition.csv'
df_100k.to_csv(output_filename, index=False)
print(f"Dataset saved as '{output_filename}' ({len(df_100k)} rows).")

